#!/usr/bin/env node
// Compare two scored run sets of one stage, made on two workflow versions: per case and
// criterion, how many runs met it in each, what changed in the stage's part of the workflow, and time and tokens.
// No overall score: a criterion that got worse is listed as worse whatever the others did.
//
//   node scripts/bench/compare.mjs --stage brief --a <runs dir> --b <runs dir> --out <report.md> [--blind <dir>] [--seed <n>]
//
// Both sets must be scored first (score.mjs --runs). --blind writes a packet for a fresh session's blind A/B read:
// packet.md holds, per case, the issue and one output from each set labelled X and Y in an order drawn from the seed;
// key.json, beside it, says which is which. Hand the packet alone to a session that has not seen either workflow.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { REPO, benchRuns, casesOf, readJson, resultOf, writeJson } from './lib.mjs';
import { rubricOf } from './score.mjs';
import { stageOf } from './stages.mjs';

/** A scored run set: [{ run, case, bench, score, result }]; throws naming a run with no score.json. */
export function scoredSet(dir) {
  const runs = benchRuns(dir);
  if (!runs.length) throw new Error(`no bench runs under ${dir}`);
  return runs.map((r) => {
    const f = join(r.dir, 'score.json');
    if (!existsSync(f)) throw new Error(`${r.dir} has no score.json: run score.mjs --runs ${dir} first`);
    return { run: r.name, case: r.bench.case, bench: r.bench, score: readJson(f).criteria, result: resultOf(r), dir: r.dir };
  });
}

/** The stage's entry (meta.actors.<stage>) in the workflow blob a run set pinned. */
export function stageEntry(set, stage) {
  const b = set[0].bench;
  const blob = join(set[0].dir, 'blobs', b.workflow.sha256);
  return existsSync(blob) ? JSON.parse(readFileSync(blob, 'utf8')).meta.actors[stage] : null;
}

/** What differs between two stage entries: rules added and removed, inputs, output fields, by JSON pointer. */
export function entryDiff(a, b) {
  const out = [];
  const ra = a?.rules ?? [];
  const rb = b?.rules ?? [];
  for (const r of ra) if (!rb.includes(r)) out.push(`- rule removed: ${r}`);
  for (const r of rb) if (!ra.includes(r)) out.push(`+ rule added: ${r}`);
  for (const k of new Set([...Object.keys(a?.inputs ?? {}), ...Object.keys(b?.inputs ?? {})])) {
    if (a?.inputs?.[k] !== b?.inputs?.[k]) out.push(`~ input ${k}: ${JSON.stringify(a?.inputs?.[k] ?? null)} -> ${JSON.stringify(b?.inputs?.[k] ?? null)}`);
  }
  const { rules: _ra, inputs: _ia, ...sa } = a ?? {};
  const { rules: _rb, inputs: _ib, ...sb } = b ?? {};
  if (JSON.stringify(sa) !== JSON.stringify(sb)) out.push('~ output schema or descriptions changed');
  return out;
}

const rate = (xs) => {
  const app = xs.filter((m) => typeof m === 'boolean');
  return { met: app.filter(Boolean).length, of: app.length };
};
const cell = (r) => (r.of ? `${r.met}/${r.of}` : 'n/a');

export function compareReport({ stage, a: allA, b: allB, aDir, bDir }) {
  const rubric = rubricOf(stage);
  // Only the cases both sets ran are compared: a set's other cases would weigh on one side only.
  const cases = [...new Set(allA.map((s) => s.case))].filter((c) => allB.some((s) => s.case === c)).sort();
  if (!cases.length) throw new Error('the two run sets have no case in common');
  const a = allA.filter((s) => cases.includes(s.case));
  const b = allB.filter((s) => cases.includes(s.case));
  const left = [...new Set([...allA, ...allB].map((s) => s.case))].filter((c) => !cases.includes(c)).sort();
  const L = [`# Bench compare: ${stage} stage`, ''];
  L.push(`Generated by \`node scripts/bench/compare.mjs --stage ${stage} --a ${relative(REPO, aDir) || aDir} --b ${relative(REPO, bDir) || bDir}\` from the two scored run sets.`, '');
  L.push(`Cases compared: ${cases.join(', ')}.${left.length ? ` Left out, run by one set only: ${left.join(', ')}.` : ''}`, '');
  for (const [n, s] of [['A', a], ['B', b]]) {
    const w = s[0].bench.workflow;
    L.push(`- ${n}: ${w.id.split('@')[0]}@${w.sha256.slice(0, 12)} (${w.source}), ${s.length} runs, model ${[...new Set(s.map((x) => x.bench.model))].join(', ')}, ambient reached ${s.filter((x) => x.bench.ambient?.reached).length}/${s.length}`);
  }
  const diff = entryDiff(stageEntry(a, stage), stageEntry(b, stage));
  L.push('', `## What changed in meta.actors.${stage}`, '', diff.length ? ['```', ...diff, '```'].join('\n') : 'Nothing: the two sets ran the same stage entry.', '');
  L.push('## Per criterion, all cases', '', '| Criterion | A | B | Change |', '|---|---|---|---|');
  const worse = [];
  for (const cr of rubric.criteria) {
    const ra = rate(a.map((s) => s.score[cr.id]?.met));
    const rb = rate(b.map((s) => s.score[cr.id]?.met));
    const fa = ra.of ? ra.met / ra.of : null;
    const fb = rb.of ? rb.met / rb.of : null;
    const change = fa == null || fb == null ? 'n/a' : fb > fa ? 'better' : fb < fa ? '**worse**' : 'same';
    if (change === '**worse**') worse.push(cr.id);
    L.push(`| ${cr.id} | ${cell(ra)} | ${cell(rb)} | ${change} |`);
  }
  L.push('', worse.length ? `Worse on: ${worse.join(', ')}. A change is kept only if no criterion is worse, or the person accepts the trade in writing.` : 'No criterion is worse.', '');
  L.push('## Per case and criterion (A -> B)', '', `| Criterion | ${cases.join(' | ')} |`, `|---|${cases.map(() => '---').join('|')}|`);
  for (const cr of rubric.criteria) {
    L.push(`| ${cr.id} | ${cases.map((c) => `${cell(rate(a.filter((s) => s.case === c).map((s) => s.score[cr.id]?.met)))} -> ${cell(rate(b.filter((s) => s.case === c).map((s) => s.score[cr.id]?.met)))}`).join(' | ')} |`);
  }
  const avg = (s, f) => (s.length ? s.reduce((n, x) => n + (f(x) ?? 0), 0) / s.length : 0);
  L.push('', '## Time and tokens per run (mean)', '', '| Set | Time | Turns | Fresh tokens | All tokens | Cost |', '|---|---|---|---|---|---|');
  for (const [n, s] of [['A', a], ['B', b]]) L.push(`| ${n} | ${(avg(s, (x) => x.bench.ms) / 1000).toFixed(0)} s | ${avg(s, (x) => x.bench.turns).toFixed(1)} | ${Math.round(avg(s, (x) => x.bench.tokens.fresh)).toLocaleString('en')} | ${Math.round(avg(s, (x) => x.bench.tokens.total)).toLocaleString('en')} | $${avg(s, (x) => x.bench.costUsd).toFixed(2)} |`);
  return { md: `${L.join('\n')}\n`, worse };
}

// A small seeded generator, so a blind packet can be made again from its seed.
const rng = (seed) => () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);

/** The blind A/B packet: per case, one output from each set as X and Y. Returns { packet, key }. */
export function blindPacket({ stage, a, b, seed = 1 }) {
  const next = rng(seed);
  const st = stageOf(stage);
  const cases = Object.fromEntries(casesOf(stage).map((c) => [c.id, c]));
  const key = {};
  const L = ['# Blind read: two outputs per case', '', st.blindIntro, ''];
  for (const id of [...new Set(a.map((s) => s.case))].sort()) {
    const sa = a.find((s) => s.case === id && s.result);
    const sb = b.find((s) => s.case === id && s.result);
    if (!sa || !sb) continue;
    const swap = next() < 0.5;
    const [x, y] = swap ? [sb, sa] : [sa, sb];
    key[id] = { X: swap ? `B ${sb.run}` : `A ${sa.run}`, Y: swap ? `A ${sa.run}` : `B ${sb.run}` };
    L.push(`## Case ${id}`, '', ...st.blindCase(cases[id]));
    for (const [n, s] of [['X', x], ['Y', y]]) L.push(`### Output ${n}`, '', ...st.blindOutput(s.result));
  }
  return { packet: `${L.join('\n')}\n`, key: { seed, key } };
}

async function main() {
  const { values: o } = parseArgs({ options: { stage: { type: 'string', default: 'brief' }, a: { type: 'string' }, b: { type: 'string' }, out: { type: 'string' }, blind: { type: 'string' }, seed: { type: 'string', default: '1' } } });
  if (!o.a || !o.b || !o.out) throw new Error('--a <dir> --b <dir> --out <file.md> are required');
  const aDir = resolve(o.a);
  const bDir = resolve(o.b);
  const a = scoredSet(aDir);
  const b = scoredSet(bDir);
  const { md, worse } = compareReport({ stage: o.stage, a, b, aDir, bDir });
  writeFileSync(resolve(o.out), md);
  process.stdout.write(md);
  if (o.blind) {
    const dir = resolve(o.blind);
    mkdirSync(dir, { recursive: true });
    const { packet, key } = blindPacket({ stage: o.stage, a, b, seed: Number(o.seed) });
    writeFileSync(join(dir, 'packet.md'), packet);
    writeJson(join(dir, 'key.json'), key);
    process.stderr.write(`[compare] blind packet: ${join(dir, 'packet.md')} (key in key.json; do not show it to the reader)\n`);
  }
  if (worse.length) process.stderr.write(`[compare] worse on: ${worse.join(', ')}\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
